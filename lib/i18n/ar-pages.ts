export const AR_PREFIX = '/ar';
const BY_SLUG = new Map(AR_DEFS.map((d) => [d.slug, d]));
const BY_EN = new Map(AR_DEFS.map((d) => [d.en, d]));

/** /ar/<slug> for an English path that has an Arabic page (any page, enabled or not), else null. */
export const arDefForEn = (enPath: string) => BY_EN.get(normPath(enPath)) || null;
export const arDefForSlug = (slug: string) => BY_SLUG.get(slug.replace(/^\/+|\/+$/g, '').toLowerCase()) ?? null;
export const arPathOf = (d: Pick<ArDef, 'slug'>) => (d.slug ? `${AR_PREFIX}/${d.slug}` : AR_PREFIX);
/** "ar", "ar/web-hosting" → the definition (theme slug as lib/theme/index.ts computes it). */
export function arDefForThemeSlug(slug: string) {
  const s = slug.toLowerCase();
  if (s === 'ar') return BY_SLUG.get('') || null;
  return s.startsWith('ar/') ? BY_SLUG.get(s.slice(3)) || null : null;
}
function normPath(p: string) {
  const x = ('/' + String(p || '/').split(/[?#]/)[0].replace(/^\/+/, '')).replace(/\/+$/, '');
  return (x || '/').toLowerCase();
}

/** Owner edits (settings.ar_pages) merged over the defaults; unknown or malformed fields are ignored. */
export type ArOverrides = Record<string, Partial<ArCopy>>;
const str = (v: unknown, max: number) => (typeof v === 'string' ? v.replace(/\s+/g, ' ').trim().slice(0, max) : '');
export function normalizeCopy(raw: unknown, d: ArCopy): ArCopy {
  const r: any = raw && typeof raw === 'object' ? raw : {};
  const s = (k: keyof ArCopy, max: number) => str(r[k], max) || (d[k] as string);
  const points = Array.isArray(r.points) ? r.points.map((p: any) => ({ icon: str(p?.icon, 30) || 'check', h: str(p?.h, 120), p: str(p?.p, 400) })).filter((p: ArPoint) => p.h && p.p).slice(0, 8) : null;
  const faqs = Array.isArray(r.faqs) ? r.faqs.map((f: any) => ({ q: str(f?.q, 200), a: str(f?.a, 1200) })).filter((f: ArQA) => f.q && f.a).slice(0, 12) : null;
  const kw = Array.isArray(r.keywords) ? r.keywords.map((k: unknown) => str(k, 80)).filter(Boolean).slice(0, 12) : null;
  return {
    title: s('title', 120), seoTitle: s('seoTitle', 70), meta: s('meta', 170), kicker: s('kicker', 80), lead: s('lead', 500), crumb: s('crumb', 60),
    keywords: kw?.length ? kw : d.keywords, pointsTitle: s('pointsTitle', 120), points: points?.length ? points : d.points,
    faqTitle: s('faqTitle', 120), faqs: faqs?.length ? faqs : d.faqs, ctaTitle: s('ctaTitle', 120), ctaText: s('ctaText', 300),
    enabled: typeof r.enabled === 'boolean' ? r.enabled : d.enabled,
  };
}
export function arPage(def: ArDef, overrides: unknown): ArDef {
  const o = overrides && typeof overrides === 'object' ? (overrides as ArOverrides)[def.slug || 'home'] : undefined;
  return { ...def, copy: normalizeCopy(o, def.copy) };
}
export const AR_SETTINGS_KEY = 'ar_pages';
/** Key used in settings.ar_pages for a page ('' → 'home'). */
export const overrideKey = (d: Pick<ArDef, 'slug'>) => d.slug || 'home';

/** Enabled Arabic pages (with the owner's edits). */
export const enabledArDefs = (overrides: unknown) => AR_DEFS.map((d) => arPage(d, overrides)).filter((d) => d.copy.enabled);

/** hreflang <link> tags for a page pair: en, ar and x-default (English). */
export function hreflangLinks(site: string, d: ArDef) {
  const en = site + (d.en === '/' ? '/' : d.en), ar = site + arPathOf(d);
  return `<link rel="alternate" hreflang="en" href="${en}"><link rel="alternate" hreflang="ar" href="${ar}"><link rel="alternate" hreflang="x-default" href="${en}">`;
}
