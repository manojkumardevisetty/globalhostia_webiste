#!/usr/bin/env node
// Static asset pipeline for the Hostpen theme (runs before `next build`, see package.json):
//   1. images: public/hp/img/*.jpg -> public/hp/img/opt/<name>-<w>.avif|webp (320/640/960/1280/1920, q≈70)
//      and lib/theme/img-manifest.ts (sizes per image, read by lib/theme/img.ts). Committed; only
//      missing or stale files are regenerated, so Vercel builds normally skip this step.
//   2. fonts: Inter + Manrope woff2 from @fontsource -> public/hp/fonts (+ fonts.css), and the
//      @font-face block at the top of public/hp/theme.css (between the @fonts markers). Committed.
//   3. lead.css: copied from the @lead block of theme.css (for WHMCS / admin; committed).
//   4. minify:public/hp/*.js|css and public/hp/pages/*.js|css -> *.min.js|css next to the
//      readable sources (gitignored). shell.ts asset() and the /hp/whmcs.* rewrites use them.
// Usage: node scripts/build-assets.mjs [--images] [--fonts] [--minify]   (no flag = all)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const HP = path.join(ROOT, 'public/hp');
const args = new Set(process.argv.slice(2));
const all = !args.size;
const newer = (src, out) => fs.existsSync(out) && fs.statSync(out).mtimeMs >= fs.statSync(src).mtimeMs;

/* ---------------------------------------------------------------- images */
// 320 only serves thumbnails (help articles, avatars); full-bleed and split images use 640+
const WIDTHS = [320, 640, 960, 1280, 1920];
async function images() {
  let sharp;
  try { sharp = (await import('sharp')).default; } catch { console.log('[assets] sharp not installed: images skipped (committed copies are used)'); return; }
  const dir = path.join(HP, 'img'), out = path.join(dir, 'opt');
  fs.mkdirSync(out, { recursive: true });
  const manifest = {};
  let made = 0;
  for (const f of fs.readdirSync(dir).filter((x) => /\.(jpe?g|png)$/i.test(x)).sort()) {
    const src = path.join(dir, f), name = f.replace(/\.[^.]+$/, '');
    const meta = await sharp(src).metadata();
    const widths = WIDTHS.filter((w) => w < meta.width);
    if (meta.width <= 1920) widths.push(meta.width); else widths.push(1920);
    const ws = [...new Set(widths)].sort((a, b) => a - b);
    for (const w of ws) {
      for (const [fmt, opts] of [['avif', { quality: 60, effort: 6 }], ['webp', { quality: 70, effort: 5 }]]) {
        const o = path.join(out, `${name}-${w}.${fmt}`);
        if (newer(src, o)) continue;
        await sharp(src).resize({ width: w, withoutEnlargement: true })[fmt](opts).toFile(o);
        made++;
      }
    }
    manifest[`/hp/img/${f}`] = { w: meta.width, h: meta.height, widths: ws, name };
  }
  // header/footer logos: drawn at ≤178px wide, so a 2x WebP (356px) replaces the 1245px PNG in the theme
  for (const f of ['logo-main-black.png', 'logo-main-white.png']) {
    const src = path.join(ROOT, 'public/image', f), o = path.join(out, f.replace('.png', '-356.webp'));
    if (fs.existsSync(src) && !newer(src, o)) { await sharp(src).resize({ width: 356 }).webp({ quality: 85, alphaQuality: 90 }).toFile(o); made++; }
  }
  const ts = `// Generated by scripts/build-assets.mjs — do not edit. Responsive variants in public/hp/img/opt.\n` +
    `export const IMG_MANIFEST: Record<string, { w: number; h: number; widths: number[]; name: string }> = ${JSON.stringify(manifest, null, 2)};\n`;
  const mf = path.join(ROOT, 'lib/theme/img-manifest.ts');
  if (!fs.existsSync(mf) || fs.readFileSync(mf, 'utf8') !== ts) fs.writeFileSync(mf, ts);
  console.log(`[assets] images: ${Object.keys(manifest).length} sources, ${made} variants written`);
}

/* ---------------------------------------------------------------- fonts */
const FONTS = [['inter', 'Inter', [400, 500, 600]], ['manrope', 'Manrope', [600, 700, 800]]];
const SUBSETS = ['latin', 'latin-ext'];
function fonts() {
  const out = path.join(HP, 'fonts');
  fs.mkdirSync(out, { recursive: true });
  const faces = [];
  for (const [pkg, family, weights] of FONTS) {
    const base = path.join(ROOT, 'node_modules/@fontsource', pkg);
    if (!fs.existsSync(base)) { console.log(`[assets] @fontsource/${pkg} missing: fonts skipped (committed copies are used)`); return; }
    for (const w of weights) {
      const css = fs.readFileSync(path.join(base, `${w}.css`), 'utf8');
      for (const sub of SUBSETS) {
        const file = `${pkg}-${sub}-${w}-normal.woff2`;
        fs.copyFileSync(path.join(base, 'files', file), path.join(out, file));
        const block = css.split('@font-face').find((b) => b.includes(`${pkg}-${sub}-${w}-normal.woff2`));
        const range = block?.match(/unicode-range:\s*([^;]+);/)?.[1].trim();
        faces.push({ family, w, file, range });
      }
    }
  }
  const face = (prefix) => faces.map((f) => `@font-face{font-family:"${f.family}";font-style:normal;font-weight:${f.w};font-display:swap;src:url(${prefix}${f.file}) format("woff2")${f.range ? `;unicode-range:${f.range}` : ''}}`).join('\n');
  fs.writeFileSync(path.join(out, 'fonts.css'), `/* Inter + Manrope (latin, latin-ext), self-hosted from @fontsource by scripts/build-assets.mjs */\n${face('')}\n`);
  const theme = path.join(HP, 'theme.css');
  const t = fs.readFileSync(theme, 'utf8');
  const blockText = `/* @fonts:start (generated by scripts/build-assets.mjs) */\n${face('fonts/')}\n/* @fonts:end */`;
  const next = /\/\* @fonts:start[\s\S]*?@fonts:end \*\//.test(t)
    ? t.replace(/\/\* @fonts:start[\s\S]*?@fonts:end \*\//, blockText)
    : t.replace(/(\*\/\n)/, `$1${blockText}\n`); // after the header comment
  if (next !== t) fs.writeFileSync(theme, next);
  console.log(`[assets] fonts: ${faces.length} files`);
}

/* ---------------------------------------------------------------- lead.css */
// The lead form / consent banner styles live in theme.css (one render-blocking file on the site);
// WHMCS (promo.js) and the admin preview load them on their own as /hp/lead.css.
function leadCss() {
  const t = fs.readFileSync(path.join(HP, 'theme.css'), 'utf8');
  const m = t.match(/\/\* @lead:start[^*]*\*\/\n([\s\S]*?)\n\/\* @lead:end \*\//);
  if (!m) { console.log('[assets] no @lead block in theme.css'); return; }
  const out = `/* Generated by scripts/build-assets.mjs from the @lead block in /hp/theme.css — edit it there. */\n${m[1]}\n`;
  const f = path.join(HP, 'lead.css');
  if (!fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== out) fs.writeFileSync(f, out);
}

/* ---------------------------------------------------------------- minify */
async function minify() {
  const { transform } = await import('esbuild');
  const files = [];
  for (const d of [HP, path.join(HP, 'pages')]) {
    for (const f of fs.readdirSync(d)) if (/\.(js|css)$/.test(f) && !/\.min\.(js|css)$/.test(f)) files.push(path.join(d, f));
  }
  let bytesIn = 0, bytesOut = 0;
  await Promise.all(files.map(async (f) => {
    const src = fs.readFileSync(f, 'utf8');
    const loader = f.endsWith('.css') ? 'css' : 'js';
    const r = await transform(src, { loader, minify: true, legalComments: 'none', target: loader === 'css' ? ['chrome100', 'safari15', 'firefox100'] : 'es2017' });
    fs.writeFileSync(f.replace(/\.(js|css)$/, '.min.$1'), r.code);
    bytesIn += src.length; bytesOut += r.code.length;
  }));
  console.log(`[assets] minified ${files.length} files: ${(bytesIn / 1024).toFixed(0)} KiB -> ${(bytesOut / 1024).toFixed(0)} KiB`);
}

if (all || args.has('--images')) await images();
if (all || args.has('--fonts')) fonts();
if (all || args.has('--fonts') || args.has('--minify')) leadCss();
if (all || args.has('--minify')) await minify();
