// Post-process the help-centre recordings (scripts/help-videos/record.mts, frames.mts) into the files the site serves:
//   public/help/videos/<slug>.mp4   H.264, CRF 28, veryfast, faststart, no audio
//   public/help/videos/<slug>.webm  VP9 fallback (skipped with --no-webm)
//   public/help/videos/<slug>.jpg   poster (frame at 60 %)
//   public/help/videos/<slug>.{en,ar}.vtt  step captions
//   public/help/frames/<name>.jpg   walkthrough screenshots
// and writes lib/help/media.ts (length, size). Usage: node scripts/help-videos/encode.mjs <raw dir> [--no-webm]
// Then add the English voice-over with scripts/help-videos/narrate.py (keep a copy of these silent files as its --src).
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const RAW = path.resolve(process.argv[2] || 'raw');
const WEBM = !process.argv.includes('--no-webm');
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..', '..');
const VID = path.join(ROOT, 'public/help/videos'), FR = path.join(ROOT, 'public/help/frames');
fs.mkdirSync(VID, { recursive: true }); fs.mkdirSync(FR, { recursive: true });
const ff = (...a) => execFileSync('ffmpeg', ['-v', 'error', '-y', ...a], { stdio: 'inherit' });
const media = {};
const today = new Date().toISOString().slice(0, 10);

for (const f of fs.readdirSync(RAW).filter((x) => x.endsWith('.json')).sort()) {
  const j = JSON.parse(fs.readFileSync(path.join(RAW, f), 'utf8'));
  const src = path.join(RAW, `${j.slug}.webm`);
  if (!j.ok || !fs.existsSync(src)) { console.log('skip', j.slug); continue; }
  const ss = String(Math.max(0, j.start)), t = String(j.dur);
  const mp4 = path.join(VID, `${j.slug}.mp4`);
  ff('-ss', ss, '-i', src, '-t', t, '-an', '-vf', 'scale=1280:720:flags=lanczos,fps=25', '-c:v', 'libx264', '-preset', 'veryfast', '-crf', '28', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', mp4);
  if (WEBM) ff('-ss', ss, '-i', src, '-t', t, '-an', '-vf', 'scale=1280:720,fps=25', '-c:v', 'libvpx-vp9', '-crf', '42', '-b:v', '0', '-deadline', 'realtime', '-cpu-used', '8', '-row-mt', '1', path.join(VID, `${j.slug}.webm`));
  ff('-ss', String(Number(ss) + j.dur * 0.6), '-i', src, '-frames:v', '1', '-vf', 'scale=1280:720', '-q:v', '5', path.join(VID, `${j.slug}.jpg`));
  for (const l of ['en', 'ar']) fs.copyFileSync(path.join(RAW, `${j.slug}.${l}.vtt`), path.join(VID, `${j.slug}.${l}.vtt`));
  const bytes = fs.statSync(mp4).size;
  media[j.slug] = { duration: Math.round(j.dur), bytes, webm: WEBM, recorded: today };
  console.log(j.slug, `${j.dur.toFixed(1)}s`, `${(bytes / 1024).toFixed(0)} KB mp4`, WEBM ? `${(fs.statSync(path.join(VID, `${j.slug}.webm`)).size / 1024).toFixed(0)} KB webm` : '');
}
const frames = path.join(RAW, 'frames');
if (fs.existsSync(frames)) for (const f of fs.readdirSync(frames).filter((x) => x.endsWith('.png'))) ff('-i', path.join(frames, f), '-q:v', '6', path.join(FR, f.replace(/\.png$/, '.jpg')));

const out = path.join(ROOT, 'lib/help/media.ts');
fs.writeFileSync(out, `// Generated by scripts/help-videos/encode.mjs: length and size of each recorded help video in public/help/videos/.
export const HELP_MEDIA: Record<string, { duration: number; bytes: number; webm: boolean; recorded: string }> = ${JSON.stringify(media, null, 2).replace(/"(\w[\w-]*)":/g, (m, k) => (/^[a-z]+$/i.test(k) ? `${k}:` : `'${k}':`))};
`);
console.log('wrote', out);
